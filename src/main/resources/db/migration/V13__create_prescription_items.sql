
CREATE TABLE prescription_items (
                                    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    version          BIGINT NOT NULL DEFAULT 0,
                                    prescription_id  BIGINT NOT NULL,
                                    medication_id    BIGINT NOT NULL,
                                    dosage           VARCHAR(100) NOT NULL,
                                    frequency        VARCHAR(100) NOT NULL,
                                    duration_days    INTEGER NOT NULL,
                                    quantity         INTEGER NOT NULL,
                                    instructions     VARCHAR(500),
                                    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
                                    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
                                    deleted          BOOLEAN NOT NULL DEFAULT FALSE,
                                    deleted_at       TIMESTAMP(6),
                                    deleted_by       BIGINT,

                                    CONSTRAINT ck_prescription_items_duration CHECK (duration_days > 0),
                                    CONSTRAINT ck_prescription_items_quantity CHECK (quantity > 0),
                                    CONSTRAINT fk_prescription_items_prescription
                                        FOREIGN KEY (prescription_id) REFERENCES prescriptions (id),
                                    CONSTRAINT fk_prescription_items_medication
                                        FOREIGN KEY (medication_id) REFERENCES medication (id)
);

CREATE INDEX idx_prescription_items_prescription ON prescription_items (prescription_id);
CREATE INDEX idx_prescription_items_medication   ON prescription_items (medication_id);

-- Partial unique index referenced in the entity comment:
-- one active line per medication per prescription.
CREATE UNIQUE INDEX uk_prescription_item_active
    ON prescription_items (prescription_id, medication_id)
    WHERE deleted = FALSE;
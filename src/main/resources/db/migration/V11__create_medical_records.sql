CREATE TABLE medical_records (
                                 id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 appointment_id  BIGINT NOT NULL,
                                 diagnosis       TEXT NOT NULL,
                                 symptoms        TEXT,
                                 treatment       TEXT,
                                 notes           TEXT,
                                 created_at      TIMESTAMP(6) NOT NULL,
                                 updated_at      TIMESTAMP(6),
                                 version         BIGINT NOT NULL DEFAULT 0,

    -- the UNIQUE constraint creates the index on appointment_id, so the
    -- separate idx_medical_record_appointment declared on the entity is redundant
                                 CONSTRAINT uk_medical_records_appointment UNIQUE (appointment_id),
                                 CONSTRAINT fk_medical_records_appointment
                                     FOREIGN KEY (appointment_id) REFERENCES appointments (id)
);

CREATE INDEX idx_medical_record_created_at ON medical_records (created_at);